HEADER = """/*
 * ESL Zap - infrared e-paper label toolkit for Flipper Zero
 * Copyright (c) 2026 SangueFreddo. Licensed under the MIT License.
 *
 * ESL Zap 5x7 font, ASCII 32..126. Generated by tools/gen_font.py.
 * Each glyph is 7 rows; bit 4 is the leftmost column.
 */
#include "ez_font.h"

const uint8_t ez_font5x7[EZ_FONT_GLYPHS][7] = {
"""


def main():
    out = [HEADER]
    for code in range(32, 127):
        ch = chr(code)
        rows = GLYPHS[ch]
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
        vals = []
        for r in rows:
            v = 0
            for c in r:
                v = (v << 1) | (1 if c == "#" else 0)
            vals.append("0x%02X" % v)
        label = ch if ch not in "\\'" else "\\" + ch
        out.append("    {%s}, /* '%s' */\n" % (", ".join(vals), label))
    out.append("};\n")
    here = os.path.dirname(os.path.abspath(__file__))
    dst = os.path.join(here, "..", "src", "image", "ez_font.c")
    with open(dst, "w") as f:
        f.write("".join(out))
    print("wrote", os.path.normpath(dst))


if __name__ == "__main__":
    main()
